/**
 * Pure helpers for the image set configuration. No file access, no dependencies, so
 * scripts/prepareImages.js, scripts/image-set-update.mjs and the unit tests share them.
 *
 * Files at the repository root:
 *   imageset.custom.json  every image set the app ships, in display order. Official sets have
 *                         their display data here (displayName, googleFont, backgroundImage) and
 *                         come from npm packages. Legacy sets are only {"legacy": true} here.
 *   imageset.legacy.json  the frozen config entries of the legacy sets, keyed by package name.
 *                         Append-only (scripts/check-fixtures-append-only.mjs): never edit an
 *                         entry. Their images are committed in public/images/<package>/.
 *   imageset.config.json  generated by scripts/prepareImages.js: the official sets from npm and
 *                         the legacy entries, merged in the order of imageset.custom.json.
 */

/** Tile shapes. Images and categories (tags) without a shape are square. */
export const SHAPES = Object.freeze(['square', 'landscape', 'portrait']);
export const DEFAULT_SHAPE = 'square';

/** npm package names of image sets: image-<lowercase letters, digits and single dashes>. */
export const PACKAGE_NAME = /^image-[a-z0-9]+(?:-[a-z0-9]+)*$/;

const isPlainObject = (value) => typeof value === 'object' && value !== null && !Array.isArray(value);
const has = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

export function isShape(value) {
  return typeof value === 'string' && SHAPES.includes(value);
}

/**
 * Splits imageset.custom.json into official and legacy package names, in order, and checks
 * that it agrees with imageset.legacy.json. Throws on any mismatch.
 */
export function splitPackages(customConfig, legacyConfig) {
  if (!isPlainObject(customConfig) || !isPlainObject(customConfig.packages)) {
    throw new Error('imageset.custom.json must be {"packages": {...}}.');
  }
  if (!isPlainObject(legacyConfig)) {
    throw new Error('imageset.legacy.json must be an object of package name -> config entry.');
  }
  const order = Object.keys(customConfig.packages);
  const official = [];
  const legacy = [];
  for (const packageName of order) {
    if (!PACKAGE_NAME.test(packageName)) {
      throw new Error(`imageset.custom.json: "${packageName}" is not an image set package name (image-...).`);
    }
    const custom = customConfig.packages[packageName];
    if (!isPlainObject(custom)) throw new Error(`imageset.custom.json: ${packageName} must be an object.`);
    if (custom.legacy === true) {
      if (!has(legacyConfig, packageName)) {
        throw new Error(`${packageName} is legacy in imageset.custom.json but has no entry in imageset.legacy.json.`);
      }
      legacy.push(packageName);
    } else {
      if (has(custom, 'legacy')) throw new Error(`imageset.custom.json: ${packageName} has "legacy": ${JSON.stringify(custom.legacy)}. Use true or leave it out.`);
      if (has(legacyConfig, packageName)) {
        throw new Error(`${packageName} has an entry in imageset.legacy.json, so imageset.custom.json must mark it {"legacy": true}.`);
      }
      official.push(packageName);
    }
  }
  for (const packageName of Object.keys(legacyConfig)) {
    if (!order.includes(packageName)) {
      throw new Error(`${packageName} is in imageset.legacy.json but not in imageset.custom.json. Legacy sets keep shipping: add "${packageName}": {"legacy": true}.`);
    }
  }
  return {order, official, legacy};
}

/** Official package names from imageset.custom.json (the sets that come from npm). */
export function officialPackages(customConfig) {
  if (!isPlainObject(customConfig) || !isPlainObject(customConfig.packages)) return [];
  return Object.entries(customConfig.packages)
    .filter(([name, custom]) => PACKAGE_NAME.test(name) && isPlainObject(custom) && custom.legacy !== true)
    .map(([name]) => name);
}

/** Checks a frozen legacy entry and returns it with "legacy": true as its last key. */
export function legacyEntry(packageName, entry) {
  if (!isPlainObject(entry) || typeof entry.displayName !== 'string' || !Array.isArray(entry.images) || !isPlainObject(entry.tags)) {
    throw new Error(`imageset.legacy.json: ${packageName} must have displayName, images and tags.`);
  }
  if (entry.images.length === 0) throw new Error(`imageset.legacy.json: ${packageName} has no images.`);
  for (const image of entry.images) {
    if (!isPlainObject(image) || typeof image.filename !== 'string' || image.filename === '') {
      throw new Error(`imageset.legacy.json: ${packageName} has an image without a filename.`);
    }
  }
  const copy = {...entry};
  delete copy.legacy;
  return {...copy, legacy: true};
}

/** The files a legacy set needs in public/images/<package>/: each image and its PNG copy for link previews. */
export function legacyFiles(entry) {
  return entry.images.flatMap(({filename}) => (
    /\.webp$/i.test(filename) ? [filename, filename.replace(/\.webp$/i, '.png')] : [filename]
  ));
}

/**
 * The shape of a tag (category) as written to imageset.config.json: its declared shape, or
 * undefined for square and for tags without a shape. Throws on an unknown shape.
 */
export function tagShape(packageName, tag) {
  if (!isPlainObject(tag) || tag.shape === undefined) return undefined;
  if (!isShape(tag.shape)) throw new Error(`${packageName}: tag "${tag.name}" has the unknown shape ${JSON.stringify(tag.shape)} (allowed: ${SHAPES.join(', ')}).`);
  return tag.shape === DEFAULT_SHAPE ? undefined : tag.shape;
}

/**
 * The shape of an image as written to imageset.config.json, or undefined for square.
 * image-set 2.2.0 and later resolve it per image (`shape`). Older packages have no shapes;
 * for them, the first of the image's tags that declares a shape counts, as in image-set.
 * Throws on an unknown shape.
 */
export function imageShape(packageName, metadata) {
  if (!isPlainObject(metadata)) return undefined;
  if (metadata.shape !== undefined) {
    if (!isShape(metadata.shape)) {
      throw new Error(`${packageName}: image "${metadata.filename}" has the unknown shape ${JSON.stringify(metadata.shape)} (allowed: ${SHAPES.join(', ')}).`);
    }
    return metadata.shape === DEFAULT_SHAPE ? undefined : metadata.shape;
  }
  for (const tag of Array.isArray(metadata.tags) ? metadata.tags : []) {
    if (isPlainObject(tag) && tag.shape !== undefined) return tagShape(packageName, tag);
  }
  return undefined;
}

/**
 * Builds the imageset.config.json entry of an official set from what its package returns:
 * `images` from getImageList(), `metadata` from getImageMetadata(). The key order and the
 * defaults are the ones the app has always written; `shape` appears only when not square.
 */
export function buildPackageEntry({packageName, displayName, images, metadata, custom = {}}) {
  if (!Array.isArray(images) || images.length === 0) {
    throw new Error(`${packageName} has no images. Check that the package version is complete.`);
  }
  if (!Array.isArray(metadata)) throw new Error(`${packageName}: getImageMetadata() did not return a list.`);
  const packageTags = {};
  const packageImages = images.map((filename) => {
    const imageMetadata = metadata.find((entry) => entry && entry.filename === filename);
    const imageTags = Array.isArray(imageMetadata?.tags) ? imageMetadata.tags : [];
    imageTags.forEach((tag) => {
      if (!packageTags[tag.name]) {
        const shape = tagShape(packageName, tag);
        packageTags[tag.name] = {
          title: tag.title || `${tag.name} for ${displayName}`,
          description: tag.description || `Description of ${tag.name} in ${displayName}`,
          category: tag.category || 'general',
          ...(shape && {shape}),
        };
      }
    });
    const shape = imageShape(packageName, imageMetadata);
    return {
      filename,
      label: imageMetadata?.label || filename,
      tags: imageTags.map((tag) => tag.name),
      ...(shape && {shape}),
    };
  });

  return {
    displayName,
    images: packageImages,
    tags: packageTags,
    // Only include googleFont and backgroundImage if they exist in imageset.custom.json
    ...(custom.googleFont && {googleFont: custom.googleFont}),
    ...(custom.backgroundImage && {backgroundImage: custom.backgroundImage}),
  };
}

/**
 * Merges the official entries (built from npm) and the frozen legacy entries in the order of
 * imageset.custom.json.
 */
export function mergeConfig(order, officialEntries, legacyConfig) {
  const packages = {};
  for (const packageName of order) {
    if (has(officialEntries, packageName)) packages[packageName] = officialEntries[packageName];
    else if (has(legacyConfig, packageName)) packages[packageName] = legacyEntry(packageName, legacyConfig[packageName]);
    else throw new Error(`No config entry for ${packageName}.`);
  }
  return {packages};
}
